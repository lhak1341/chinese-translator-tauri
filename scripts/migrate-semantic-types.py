#!/usr/bin/env python3
"""
Migrate semantic type values in dictionary files:
  'person' -> 'character'
  'place'  -> 'location'

Skips .trie.json files (auto-regenerated by the app).
Creates .bak backups before modifying any file.
"""

import json
import os
import shutil

DICT_DIR = os.path.expanduser(
    '~/Library/Application Support/com.lhak.chinese-translator/dictionaries'
)

RENAMES = {
    'person': 'character',
    'place': 'location',
}


def migrate_file(path):
    try:
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        print(f'  WARNING: skipping {os.path.basename(path)}: {e}')
        return 0

    changed = 0
    for key, value in data.items():
        if isinstance(value, dict) and 'semanticType' in value:
            old = value['semanticType']
            if old in RENAMES:
                value['semanticType'] = RENAMES[old]
                changed += 1

    if changed:
        shutil.copy2(path, path + '.bak')
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

    return changed


def main():
    files = sorted(
        f for f in os.listdir(DICT_DIR)
        if f.endswith('.json') and not f.endswith('.trie.json')
    )

    total_files = 0
    total_entries = 0

    for filename in files:
        path = os.path.join(DICT_DIR, filename)
        changed = migrate_file(path)
        if changed:
            print(f'  {filename}: {changed} entries updated')
            total_files += 1
            total_entries += changed

    print(f'\nDone: {total_entries} entries updated across {total_files} files.')
    if total_entries:
        print('Backups saved as <filename>.bak')
    print('\nReload dictionaries in the app (Cmd-R) before translating.')


if __name__ == '__main__':
    main()
