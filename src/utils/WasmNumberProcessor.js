import { verifyWasmInstance, verifyWasmBinaryIntegrity } from './wasmIntegrityVerifier'; // CODE REVIEW FIX: WASM integrity verification

let wasmNumberProcessor = null;
let initializationPromise = null;
let initializationFailed = false;
let showedNumberWarning = false;
// CODE REVIEW FIX (CRITICAL-1): Prevent race condition in promise cache clearing
let retryAllowedAfter = 0;
const RETRY_COOLDOWN_MS = 5000; // 5 seconds

/**
 * Initialize the WASM NumberProcessor
 * @returns {Promise<boolean>} True if initialization succeeded
 */
export async function initializeWasmNumberProcessor() {
  // Return cached result if already initialized or failed
  if (wasmNumberProcessor) {
    return true;
  }
  if (initializationFailed) {
    return false;
  }

  // CODE REVIEW FIX (2026-02-01): Check cooldown period before creating promise
  // This prevents rapid retry attempts from bypassing the backoff mechanism
  if (retryAllowedAfter > Date.now()) {
    const remainingMs = retryAllowedAfter - Date.now();
    logger.warn(
      `⏳ WASM NumberProcessor initialization on cooldown (${Math.ceil(remainingMs / 1000)}s remaining)`
    );
    return false;
  }

  // Return existing promise if initialization in progress
  if (initializationPromise) {
    return initializationPromise;
  }

  // RACE CONDITION FIX: Assign promise synchronously before async work
  // This prevents concurrent calls from creating multiple initialization attempts
  return (initializationPromise = (async () => {
    try {
      // CODE REVIEW FIX (HIGH-4): Wrap initialization in retry logic
      await wasmRetryManager.retryWithBackoff(
        async () => {
          logger.log('🔢 Initializing WASM NumberProcessor...');

          // CODE REVIEW FIX (CRITICAL-1): Fetch WASM binary for hash verification
          const wasmFileName = 'translation_wasm_core_bg.wasm';
          const wasmUrl = new URL(`../wasm/${wasmFileName}`, import.meta.url);

          logger.debug('Fetching WASM binary for integrity verification...');
          const response = await fetch(wasmUrl);
          if (!response.ok) {
            throw new Error(`Failed to fetch WASM: ${response.statusText}`);
          }

          const wasmBinary = await response.arrayBuffer();
          logger.debug(`WASM binary fetched (${wasmBinary.byteLength} bytes)`);

          // CODE REVIEW FIX (CRITICAL-1): Verify binary integrity with SHA-256
          const integrityCheck = await verifyWasmBinaryIntegrity(wasmFileName, wasmBinary);
          if (!integrityCheck.valid) {
            throw new Error(
              `WASM binary integrity check failed: ${integrityCheck.errors.join(', ')}`
            );
          }
          if (integrityCheck.warnings.length > 0) {
            logger.warn('WASM integrity warnings:', integrityCheck.warnings);
          }

          // Initialize WASM module with verified binary
          logger.debug('Initializing WASM module with verified binary...');
          await init(wasmBinary);
          logger.debug('WASM module initialized successfully');

          // Create NumberProcessor instance
          logger.debug('Creating NumberProcessor instance...');
          wasmNumberProcessor = new NumberProcessor();
          logger.debug('NumberProcessor instance created');

          // CODE REVIEW FIX: Verify instance has expected methods
          const instanceVerification = verifyWasmInstance(
            wasmNumberProcessor,
            ['processTokens', 'free'],
            'NumberProcessor'
          );
          if (!instanceVerification.valid) {
            throw new Error(
              `WASM instance verification failed: ${instanceVerification.errors.join(', ')}`
            );
          }

          logger.log('✅ WASM NumberProcessor initialized successfully');
        },
        'NumberProcessor-init',
        { onlyRetryTransient: true }
      );

      // Reset warning flag on successful initialization
      showedNumberWarning = false;

      return true;
    } catch (error) {
      logger.warn('⚠️ Failed to initialize WASM NumberProcessor after retries:', error);
      logger.warn('Falling back to character-by-character translation for numbers');
      initializationFailed = true;
      return false;
    }
  })());
}

/**
 * Process tokens to convert Chinese numbers
 * @param {Array} tokens - Array of token objects
 * @returns {Promise<Array>} Processed tokens
 */
export async function processNumbersWasm(tokens) {
  // Ensure WASM is initialized
  if (!wasmNumberProcessor) {
    const success = await initializeWasmNumberProcessor();
    if (!success) {
      // One-time notification for initialization failure
      if (!showedNumberWarning) {
        toast.warning(
          'Number processing unavailable. Numbers will translate character-by-character.',
          {
            duration: TOAST_DURATIONS.LOAD_FAILURE,
            id: TOAST_IDS.WASM_NUMBER_FALLBACK,
          }
        );
        showedNumberWarning = true;
      }

      // WASM failed - return tokens unchanged
      return tokens;
    }
  }

  try {
    // CODE REVIEW NOTE (MEDIUM-4): Performance degradation monitoring
    // TODO: Add performance tracking here:
    // const startTime = performance.now();
    // const processedTokens = wasmNumberProcessor.processTokens(tokens);
    // const duration = performance.now() - startTime;
    //
    // if (typeof window !== 'undefined' && window.systemPerformanceMonitor) {
    //   window.systemPerformanceMonitor.recordMetric('wasm_number_processing', duration);
    //   // Check if duration > baseline * 2
    //   // If degraded, log warning: "WASM number processor slowdown detected"
    // }

    // Call WASM NumberProcessor
    const processedTokens = wasmNumberProcessor.processTokens(tokens);
    return processedTokens;
  } catch (error) {
    // CODE REVIEW FIX (MEDIUM-1): Use shared error categorization
    const errorInfo = categorizeWasmError(error, 'number-processor');

    logger.error(`❌ WASM number processing ${errorInfo.type} error:`, error);

    // Report to error tracking if needed (Sentry, etc.)
    if (errorInfo.shouldReport && typeof window !== 'undefined' && window.errorTracker) {
      window.errorTracker.captureException(error, {
        tags: { component: errorInfo.component, error_type: errorInfo.type },
      });
    }

    // One-time notification for processing errors with specific message
    if (!showedNumberWarning) {
      const detailedMessage = `${formatWasmError(errorInfo)}. Numbers will translate character-by-character.`;
      toast.warning(detailedMessage, {
        duration: TOAST_DURATIONS.LOAD_FAILURE,
        id: TOAST_IDS.WASM_NUMBER_FALLBACK,
      });
      showedNumberWarning = true;
    }

    // Fallback: return tokens unchanged
    return tokens;
  }
}

/**
 * Check if WASM NumberProcessor is available
 * @returns {boolean} True if WASM is loaded and ready
 */
export function isWasmNumberProcessorAvailable() {
  return wasmNumberProcessor !== null;
}

/**
 * Check if WASM initialization failed
 * @returns {boolean} True if initialization failed
 */
export function hasWasmNumberProcessorFailed() {
  return initializationFailed;
}

/**
 * Get WASM NumberProcessor status
 * @returns {Object} Status information
 */
export function getWasmNumberProcessorStatus() {
  return {
    available: wasmNumberProcessor !== null,
    failed: initializationFailed,
    initializing: initializationPromise !== null && wasmNumberProcessor === null,
  };
}

/**
 * Re-initialize WASM NumberProcessor
 * @returns {Promise<boolean>} True if re-initialization succeeded
 */
export async function reinitializeWasmNumberProcessor() {
  // CODE REVIEW FIX (CRITICAL-1): Check cooldown period before allowing retry
  if (retryAllowedAfter > Date.now()) {
    const remainingMs = retryAllowedAfter - Date.now();
    logger.warn(
      `⏳ WASM NumberProcessor retry on cooldown (${Math.ceil(remainingMs / 1000)}s remaining)`
    );
    return false;
  }

  // Clear existing state
  wasmNumberProcessor = null;
  initializationPromise = null;
  initializationFailed = false;
  showedNumberWarning = false; // Reset warning flag to allow new notifications
  retryAllowedAfter = 0; // Reset cooldown

  // Re-initialize
  return initializeWasmNumberProcessor();
}

/**
 * Clean up WASM NumberProcessor resources
 * CODE REVIEW FIX (MEDIUM-7): Added cleanup method for consistency
 * @returns {void}
 */
export function cleanupWasmNumberProcessor() {
  wasmNumberProcessor = null;
  initializationPromise = null;
  initializationFailed = false;
  showedNumberWarning = false;

  logger.log('🧹 WASM NumberProcessor cleaned up');
  // Note: No intervals to clear in this module
}

// Auto-initialize on import (non-blocking)
// CODE REVIEW FIX (CRITICAL-1): Use cooldown period to prevent race condition in promise cache clearing
initializeWasmNumberProcessor().catch((err) => {
  logger.warn('Background WASM NumberProcessor initialization failed:', err);
  initializationFailed = true; // Mark initialization as failed to prevent retries
  wasmNumberProcessor = null; // Clear partial state

  // CODE REVIEW FIX (CRITICAL-1): Set cooldown before clearing promise cache
  // This prevents concurrent imports during same module load cycle from creating duplicate initialization attempts
  retryAllowedAfter = Date.now() + RETRY_COOLDOWN_MS;
  setTimeout(() => {
    initializationPromise = null; // Clear cache after cooldown
  }, RETRY_COOLDOWN_MS);
});
