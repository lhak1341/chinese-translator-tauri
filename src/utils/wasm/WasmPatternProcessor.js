import toast from '../toast';
import { logger } from '../logger';
import { verifyWasmModule } from './wasmIntegrityVerifier';
import { fetchWasmBinary } from './wasmBinaryCache';
import { callWasmWithTimeout, DEFAULT_WASM_TIMEOUTS } from './wasmOperationTimeout';
import { WasmProcessorLifecycle } from './WasmProcessorLifecycle';
import { wasmTextAssembler } from './WasmTextAssembler';
import { wasmTextChunker } from './WasmTextChunker';
import { retireWasmDictionaryOnSharedPanic } from './WasmDictionaryManager';
import { retireWasmConflictResolutionOnSharedPanic } from './WasmConflictResolution';
import { registerCascadeHandler, fireCascadeRetire } from './WasmCascadeRegistry';

// Static literal required so Vite transforms import.meta.url to the correct asset URL in production
const _WASM_BINARY_URL = new URL('../../wasm/translation_wasm_core_bg.wasm', import.meta.url);

const lifecycle = new WasmProcessorLifecycle({
  name: 'PatternProcessor',
  wasmFileName: 'translation_wasm_core_bg.wasm',
  wasmBinaryUrl: _WASM_BINARY_URL,
  expectedMethods: ['initialize', 'processTokens', 'getStatistics', 'free'],
});

let wasmModule = null;
let wasmPatternProcessor = null;
let lastPatternWarningTime = 0;
const PATTERN_WARNING_COOLDOWN = 10 * 60 * 1000; // 10 minutes
registerCascadeHandler(() => {
  wasmPatternProcessor = null;
  lifecycle.permanentlyFail();
});

/**
 * Initialize the WASM Pattern Processor
 * @param {Object} patternsDict - Pattern dictionary (e.g., {"X的Y": "Y của X"})
 * @returns {Promise<boolean>} True if initialization succeeded
 */
export async function initializeWasmPatternProcessor(patternsDict) {
  const success = await lifecycle.initialize(async (wasmBinary) => {
    // Dynamic import required here — Pattern needs verifyWasmModule before init
    wasmModule = await import('../../wasm/translation_wasm_core.js');

    const moduleVerification = verifyWasmModule(wasmModule, 'translation_wasm_core');
    if (!moduleVerification.valid) {
      throw new Error(
        `WASM module integrity check failed: ${moduleVerification.errors.join(', ')}`
      );
    }

    logger.debug('Initializing WASM module with verified binary...');
    await wasmModule.default(wasmBinary);

    const instance = new wasmModule.WasmPatternProcessor();

    const patternSuccess = instance.initialize(JSON.stringify(patternsDict));
    if (!patternSuccess) {
      throw new Error('Failed to initialize pattern processor with patterns');
    }

    logger.log('✅ WASM Pattern Processor initialized successfully');
    wasmPatternProcessor = instance;
    return instance;
  });

  if (success) {
    lastPatternWarningTime = 0;
  } else {
    wasmPatternProcessor = null;
    wasmModule = null;
    logger.error('Pattern matching will not be available. Please check WASM configuration.');
  }

  return success;
}

// MEDIUM FIX: Toast duration constants
const TOAST_DURATION = {
  ERROR: 10000,
  WARNING: 5000,
  INFO: 3000,
};

/**
 * Process semantic tokens with two-phase pattern matching
 * @param {Array} semanticTokens - Array of semantic token objects
 * @param {Object} variableCache - Variable translation cache
 * @returns {Promise<Object>} Result object with { success: boolean, results: Array, error?: string }
 */
export async function processTokensWasm(semanticTokens, variableCache) {
  // CRITICAL-2 FIX: Degrade gracefully instead of throwing
  // Patterns enhance translation quality but aren't essential - allow basic translation to continue

  // Wait for in-progress initialization before degrading
  if (lifecycle.pendingInit && !wasmPatternProcessor) {
    const success = await lifecycle.pendingInit;

    // CRITICAL: Verify initialization actually succeeded
    if (!success || !wasmPatternProcessor) {
      const errorMsg = 'WASM Pattern Processor initialization failed - skipping pattern processing';
      logger.warn(`⚠️ ${errorMsg}`);
      logger.warn('Translation will continue with lower quality (no pattern matching)');

      // CODE REVIEW FIX (HIGH-1): Add user notification for initialization failure
      const now = Date.now();
      if (now - lastPatternWarningTime > PATTERN_WARNING_COOLDOWN) {
        toast.warning(
          'Pattern matching initialization failed. Translation quality may be reduced.',
          {
            duration: TOAST_DURATION.WARNING,
          }
        );
        lastPatternWarningTime = now;
      }

      return {
        success: false,
        results: [],
        error: errorMsg,
      };
    }
  }

  if (!wasmPatternProcessor) {
    const errorMsg = 'WASM Pattern Processor not initialized - skipping pattern processing';
    logger.warn(`⚠️ ${errorMsg}`);
    logger.warn('Translation will continue with lower quality (no pattern matching)');

    // MEDIUM-3 FIX: Show warning with cooldown instead of once-per-session
    const now = Date.now();
    if (now - lastPatternWarningTime > PATTERN_WARNING_COOLDOWN) {
      toast.warning('Pattern matching unavailable. Translation quality may be reduced.', {
        duration: TOAST_DURATION.WARNING,
      });
      lastPatternWarningTime = now;
    }

    // MEDIUM FIX: Return structured error object instead of empty array
    return {
      success: false,
      results: [],
      error: errorMsg,
    };
  }

  try {
    // Call WASM Pattern Processor with timeout protection.
    // NOTE: processTokens() is synchronous WASM — JavaScript cannot pre-empt a running
    // synchronous WASM call, so the timeout fires only after WASM returns. This wrapper
    // does NOT protect against truly hung (infinite-loop) WASM, but it does:
    //   1. Document the intended time budget for pattern processing
    //   2. Provide a graceful fallback if a future async refactor makes the call interruptible
    //   3. Protect against edge cases where processTokens returns a rejected Promise
    // processTokens takes/returns JSON strings — zero JS interop inside WASM Rc borrow window
    const results = await callWasmWithTimeout(
      () =>
        JSON.parse(
          wasmPatternProcessor.processTokens(
            JSON.stringify(semanticTokens),
            JSON.stringify(variableCache)
          )
        ),
      DEFAULT_WASM_TIMEOUTS.PATTERN_MATCHING,
      'pattern-processing',
      { throwOnTimeout: false, fallbackValue: [] }
    );
    return {
      success: true,
      results: results ?? [],
    };
  } catch (error) {
    const errorMsg = `WASM pattern processing error: ${error.message}`;
    logger.error('❌ Error in WASM pattern processing, skipping patterns:', error);
    wasmPatternProcessor = null;
    lifecycle.permanentlyFail();
    wasmTextAssembler.retireOnSharedModulePanic();
    wasmTextChunker.retireOnSharedModulePanic();
    retireWasmDictionaryOnSharedPanic();
    retireWasmConflictResolutionOnSharedPanic();
    fireCascadeRetire();

    // MEDIUM-3 FIX: Show warning with cooldown instead of once-per-session
    const now = Date.now();
    if (now - lastPatternWarningTime > PATTERN_WARNING_COOLDOWN) {
      toast.warning('Pattern matching error. Translation quality may be reduced.', {
        duration: TOAST_DURATION.WARNING,
      });
      lastPatternWarningTime = now;
    }

    // MEDIUM FIX: Return structured error object
    // Log error but don't block translation - patterns are quality enhancement
    // Translation can continue without patterns (proper nouns + phrases + characters still work)
    return {
      success: false,
      results: [],
      error: errorMsg,
    };
  }
}

/**
 * Check if WASM Pattern Processor is available
 * @returns {boolean} True if WASM is loaded and ready
 */
export function isWasmPatternProcessorAvailable() {
  return lifecycle.isReady && wasmPatternProcessor !== null;
}

/**
 * Check if WASM initialization failed
 * @returns {boolean} True if initialization failed
 */
export function hasWasmPatternProcessorFailed() {
  return lifecycle.hasFailed;
}

/**
 * Check if WASM Pattern Processor is ready to use (available and not failed)
 * @returns {boolean} True if WASM is loaded, initialized, and has not failed
 */
export function isWasmPatternProcessorReady() {
  return lifecycle.isReady;
}

/**
 * Get pattern processor statistics
 * @returns {Object|null} Statistics object or null if not initialized
 */
export function getWasmPatternProcessorStats() {
  if (!wasmPatternProcessor) {
    return null;
  }

  try {
    return JSON.parse(wasmPatternProcessor.getStatistics());
  } catch (error) {
    logger.error('❌ Error getting WASM pattern processor stats:', error);
    return null;
  }
}

/**
 * Re-initialize pattern processor with new patterns
 * @param {Object} patternsDict - New pattern dictionary
 * @returns {Promise<boolean>} True if re-initialization succeeded
 */
export async function reinitializeWasmPatternProcessor(patternsDict) {
  if (!lifecycle.reset()) return false;
  wasmPatternProcessor = null;
  wasmModule = null;
  lastPatternWarningTime = 0;
  return initializeWasmPatternProcessor(patternsDict);
}

// Pre-warm WASM module and binary cache at import time so the first
// initializeWasmPatternProcessor call (which requires patternsDict) doesn't
// block on network I/O during the critical translation path.
// Does NOT call wasmModule.default() or create WasmPatternProcessor instances —
// those steps require patternsDict and happen in initializeWasmPatternProcessor.
(async () => {
  try {
    await import('../../wasm/translation_wasm_core.js'); // warms ES module cache
    await fetchWasmBinary(_WASM_BINARY_URL); // warms binary cache
    logger.debug('🔥 WASM PatternProcessor module and binary pre-warmed');
  } catch (err) {
    logger.warn('WASM PatternProcessor pre-warm failed (non-critical):', err);
  }
})();
