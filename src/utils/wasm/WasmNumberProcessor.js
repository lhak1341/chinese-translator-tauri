import init, { NumberProcessor } from '../../wasm/translation_wasm_core.js';
import toast from '../toast';
import { logger } from '../logger';
import { TOAST_DURATIONS, TOAST_IDS } from '../../constants/toastConfig';
import { categorizeWasmError, formatWasmError } from './wasmErrorHandler';
import { WasmProcessorLifecycle } from './WasmProcessorLifecycle';
import { wasmTextAssembler } from './WasmTextAssembler';
import { wasmTextChunker } from './WasmTextChunker';
import { retireWasmDictionaryOnSharedPanic } from './WasmDictionaryManager';
import { retireWasmConflictResolutionOnSharedPanic } from './WasmConflictResolution';
import { registerCascadeHandler, fireCascadeRetire } from './WasmCascadeRegistry';

// Static literal required so Vite transforms import.meta.url to the correct asset URL in production
const _WASM_BINARY_URL = new URL('../../wasm/translation_wasm_core_bg.wasm', import.meta.url);

const lifecycle = new WasmProcessorLifecycle({
  name: 'NumberProcessor',
  wasmFileName: 'translation_wasm_core_bg.wasm',
  wasmBinaryUrl: _WASM_BINARY_URL,
  expectedMethods: ['processTokens', 'free'],
});

/** @type {NumberProcessor|null} */
let wasmNumberProcessor = null;
let showedNumberWarning = false;
registerCascadeHandler(() => {
  wasmNumberProcessor = null;
  lifecycle.permanentlyFail();
});

async function initializeWasmNumberProcessor() {
  const success = await lifecycle.initialize(async (wasmBinary) => {
    logger.log('🔢 Initializing WASM NumberProcessor...');
    await init(wasmBinary);
    const instance = new NumberProcessor();
    logger.log('✅ WASM NumberProcessor initialized successfully');
    wasmNumberProcessor = instance;
    return instance;
  });

  if (success) {
    showedNumberWarning = false;
  } else {
    wasmNumberProcessor = null;
    logger.warn('Falling back to character-by-character translation for numbers');
  }

  return success;
}

/**
 * Process tokens to convert Chinese numbers
 * @param {Array<*>} tokens - Array of token objects
 * @returns {Promise<Array<*>>} Processed tokens
 */
export async function processNumbersWasm(tokens) {
  // Ensure WASM is initialized
  if (!wasmNumberProcessor) {
    const success = await initializeWasmNumberProcessor();
    if (!success) {
      // One-time notification for initialization failure
      if (!showedNumberWarning) {
        toast.warning(
          'Number processing unavailable. Numbers will translate character-by-character.',
          {
            duration: TOAST_DURATIONS.LOAD_FAILURE,
            id: TOAST_IDS.WASM_NUMBER_FALLBACK,
          }
        );
        showedNumberWarning = true;
      }

      // WASM failed - return tokens unchanged
      return tokens;
    }
  }

  try {
    // CODE REVIEW NOTE (MEDIUM-4): Performance degradation monitoring
    // TODO: Add performance tracking here:
    // const startTime = performance.now();
    // const processedTokens = wasmNumberProcessor.processTokens(tokens);
    // const duration = performance.now() - startTime;
    //
    // if (typeof window !== 'undefined' && window.systemPerformanceMonitor) {
    //   window.systemPerformanceMonitor.recordMetric('wasm_number_processing', duration);
    //   // Check if duration > baseline * 2
    //   // If degraded, log warning: "WASM number processor slowdown detected"
    // }

    // Call WASM NumberProcessor (null check narrows type for @ts-check — logically unreachable)
    if (!wasmNumberProcessor) return tokens;
    // processTokens takes/returns JSON strings — zero JS interop inside WASM Rc borrow window
    const processedTokens = wasmNumberProcessor.processTokens(JSON.stringify(tokens));
    return JSON.parse(processedTokens);
  } catch (/** @type {any} */ error) {
    // Retire the broken instance — after a WASM panic, the shared linear memory is
    // permanently corrupted. permanentlyFail() (not reset()) prevents re-initialization
    // from the corrupted module on subsequent translations.
    wasmNumberProcessor = null;
    lifecycle.permanentlyFail();
    // Both processors share one WASM module — a NumberProcessor panic corrupts the shared
    // linear memory, so the TextAssembler will also panic on its next call. Retire it now
    // to avoid the secondary panic and go straight to JS fallback.
    wasmTextAssembler.retireOnSharedModulePanic();
    wasmTextChunker.retireOnSharedModulePanic();
    retireWasmDictionaryOnSharedPanic();
    retireWasmConflictResolutionOnSharedPanic();
    fireCascadeRetire();

    const errorInfo = categorizeWasmError(error, 'number-processor');

    logger.error(`❌ WASM number processing ${errorInfo.type} error:`, error);

    // Report to error tracking if needed (Sentry, etc.)
    // @ts-ignore - window.errorTracker is an optional runtime debug property
    if (errorInfo.shouldReport && typeof window !== 'undefined' && window.errorTracker) {
      // @ts-ignore
      window.errorTracker.captureException(error, {
        tags: { component: errorInfo.component, error_type: errorInfo.type },
      });
    }

    // One-time notification for processing errors with specific message
    if (!showedNumberWarning) {
      const detailedMessage = `${formatWasmError(errorInfo)}. Numbers will translate character-by-character.`;
      toast.warning(detailedMessage, {
        duration: TOAST_DURATIONS.LOAD_FAILURE,
        id: TOAST_IDS.WASM_NUMBER_FALLBACK,
      });
      showedNumberWarning = true;
    }

    // Fallback: return tokens unchanged
    return tokens;
  }
}

/**
 * Check if WASM NumberProcessor is available
 * @returns {boolean} True if WASM is loaded and ready
 */
export function isWasmNumberProcessorAvailable() {
  return lifecycle.isReady && wasmNumberProcessor !== null;
}

// Auto-initialize on import (non-blocking)
initializeWasmNumberProcessor().catch((err) => {
  logger.warn('Background WASM NumberProcessor initialization failed:', err);
  wasmNumberProcessor = null;
});
